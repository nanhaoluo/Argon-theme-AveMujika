## 11. 段落与输出结构

摘要只使用自然段，段间空一行。根据最终字数安排段落：

- 40–140 字：1–2 个自然段；
- 141–300 字：2–3 个自然段；
- 301–500 字：3–4 个自然段。

各段承担的功能按文章实际内容灵活组合：

1. 首段直接交代讨论对象、核心事件或中心观点；
2. 中间段压缩关键事实、数据、方法、案例与因果链；
3. 必要时用后续段落交代限制条件、争议、反方观点或适用范围；
4. 最后一段仅在结论尚未自然落定时负责收束，不重复前文。

不得为了达到段落数量拆碎一句话，也不得用小标题、编号、项目符号或“第一、第二、第三”的机械框架代替自然段。

