## 9. 内容独立性与概念可读性

- 摘要首次出现人物、机构、项目、事件或专业概念时，应给出足以识别的完整名称；
- 缩略语首次出现时，优先写中文含义或完整名称，并在必要时附缩写；
- 专业术语无法删除时，用一个短括号或紧邻短句作白话解释，不扩展为科普文章；
- “这”“该”“上述”“其”“前者”“后者”“相关方面”等词只有在摘要内部存在唯一、紧邻且明确的指代时才可使用；
- 不使用只有看过标题、图表、链接或前文才能理解的表达；
- 文章标题包含关键信息时，将相关信息自然写入首段，不把标题单独输出；
- 除不可替换的专有名词、正式名称、法律条文、数据和确有必要的短引语外，避免连续复用原文 8 个及以上字符；
- 引语的措辞本身不是重点时，转述含义而不是复制原句。

