## 7. 不同文章类型的提取重点

先识别文章类型，再选择相关要素；不要为了套模板而强行补齐原文没有的信息。

### 新闻与事件报道

优先保留事件主体、发生了什么、时间地点、关键进展、直接原因、重要数据、各方明确表态、当前结果与尚未确定的事项。传闻、预测和官方确认必须区分，不能把“据称”“可能”“预计”改写为确定事实。

### 评论、社论与观点文章

优先保留作者的中心论点、主要论据、推理链、针对的对象、回应的反方观点、成立前提与最终主张。必须明确属于作者判断的内容，不得用客观事实语气替作者背书。

### 科研、技术与学术文章

优先保留研究问题、方法、样本或数据来源、关键发现、量化结果、创新点、适用范围和作者承认的局限。相关性不得改写为因果性，实验结果不得扩大到原文没有覆盖的人群、环境或场景。

### 教程、指南与操作说明

优先保留目标、适用对象、必要前提、关键步骤之间的关系、重要参数、风险点和预期结果。摘要只概括教程，不执行步骤，不生成额外命令，也不把示例代码大段复制到摘要中。

### 产品、政策、公告与规则说明

优先保留发布主体、适用对象、生效时间、核心变化、资格条件、费用或限制、执行方式、例外情况和对相关群体的直接影响。宣传性形容词应删除；尚未实施的计划不得写成已经落地。

### 评测、比较与方案分析

优先保留比较对象、比较标准、关键差异、数据依据、适用场景、优势限制和文章结论。不能把局部指标领先概括为整体更优，也不能删除会改变推荐结果的使用条件。

### 访谈、演讲与问答记录

优先保留发言者身份、核心观点、关键事实、立场差异和最终判断。删除寒暄、重复追问和无信息量互动；不得把采访者的问题当成受访者认可的事实。

### 叙事、人物与案例文章

优先保留核心人物、主要事件、必要时间线、关键转折、行为动机中原文明示的部分，以及文章借个案表达的结论。氛围描写和细节只在影响人物选择或结论时保留。

