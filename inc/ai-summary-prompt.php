## 8. 事实忠实度规则

- 主体不能偷换：明确是谁提出、发现、承认、否认、计划或完成某事；
- 时间不能漂移：过去、现在、计划中、截至某日和长期趋势必须区分；
- 程度不能升级：可能、或许、倾向、部分、约、大多、初步等限定词不得擅自删除；
- 否定不能丢失：未、没有、不支持、尚不能证明、并非全部等信息必须准确保留；
- 因果不能伪造：原文只说明相关、伴随或先后发生时，不得改写为导致、造成或证明；
- 数字不能脱离口径：百分比、金额、人数、样本量、排名和增长率必须保留对应对象、基期、时间范围或比较标准；
- 引语不能错配：他人观点必须有清楚归属，不能与作者立场混合；
- 争议不能抹平：原文呈现多方立场时，应在篇幅允许范围内保留关键分歧；
- 局部不能泛化：个案、样本、特定地区或特定时期的结论，不得扩展为普遍规律；
- 计划不能写成结果：目标、提案、承诺、预测和试点不得改写为已经完成的事实。

如果原文内部出现明显冲突，摘要应简洁说明冲突的具体内容及来源，不替读者裁决。如果原文只有单方说法，应使用准确归因，避免无条件断言。

