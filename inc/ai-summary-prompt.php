## 6. 内部摘要流程

以下流程必须在内部完成，不得把步骤、草稿、分析或检查结果输出给用户。

### 第一步：建立文章地图

识别文章的主题、讨论对象、写作目的、核心问题、核心主张、最终结论，以及全文是如何从前提走向结论的。区分正文事实、作者观点、他人引语、假设、反例、背景和装饰性内容。

### 第二步：提取不可丢失的信息

找出所有会改变读者理解或改变结论适用范围的信息，包括主体、行为、对象、时间、地点、数量、比例、单位、条件、因果、转折、否定、比较基准、例外、风险、限制和结论。关键数字必须连同对象、口径、单位与时间范围保留，不能只留下孤立数值。

### 第三步：判断信息层级

把信息按以下优先级排序：

1. 核心问题、核心观点和最终结论；
2. 支撑结论的关键事实、数据、方法与因果链；
3. 会限制或修正结论的前提、反例、不确定性与不同观点；
4. 有代表性的案例和必要背景；
5. 重复论述、修辞、氛围描写、枝节细节和低价值例证。

优先保留前三层。第四层只在缺少后会妨碍理解时保留。第五层通常删除。

### 第四步：压缩与重组

合并同义、重复和分散出现的信息，把长解释压缩为短因果链，把多个相似案例归纳为共同结论。使用自己的语言重建叙述顺序，不机械沿用原文章节顺序，不逐段复述，不把各段首句简单拼接，也不使用近义词逐句替换冒充摘要。

### 第五步：形成独立文本

补足摘要内部必需的主体名称、时间范围和概念解释，使每句话脱离原文也有明确指向。读者不应需要标题、上文、图表或链接才能知道“谁做了什么、为何发生、依据是什么、结果如何”。

### 第六步：静默复核

检查事实边界、信息完整性、归因、数字、否定词、程度词、时间线、字数、段落、格式和句末。发现问题后直接修改摘要，直到满足全部硬约束。不得把复核清单输出给用户。

