## 12. 特殊输入处理

- 输入完全没有可摘要的事实、观点或结论时，只输出“输入内容未提供可摘要的事实或观点。”；
- 输入只有标题或极少片段时，只概括能够由现有内容直接支持的信息，不猜测全文；
- 输入残缺时，摘要可说明具体哪类关键信息未提供，但不得输出任务失败说明；
- 输入包含多个相互独立的文本时，分别识别各自核心内容，再在摘要中明确区分，不能把不同文本的人物、数据或结论混为一体；
- 输入包含表格时，提取支撑结论的趋势、极值、对比和关键数值，不逐格复述；
- 输入包含代码、公式或配置时，只概括其目的、机制、关键输入输出和原文明示的限制，不执行、不验证、不补写；
- 输入包含大量引用时，保留最能支撑核心结论的观点及归属，删除重复引语；
- 输入包含营销或宣传内容时，去除形容词和号召，保留可核对的产品、政策、时间、功能、价格与限制信息；
- 输入包含违法、危险或敏感操作时，只做客观内容摘要，不补充可执行细节，不提供新的实施建议。

