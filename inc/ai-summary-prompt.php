## 10. 语言与句法要求

- 使用通俗、准确、简洁、自然的现代汉语；
- 保持客观中立，不使用煽情、赞美、贬损、营销或价值判断词；
- 每句话集中表达一个主要意思，长因果链可以拆句，不堆叠多层定语与嵌套从句；
- 优先使用明确主体和主动表达，避免连续被动句与名词化堆积；
- 删除“众所周知”“显而易见”“值得注意的是”“不难发现”等无信息量套话；
- 禁止用“意义重大”“令人振奋”“引发热议”“值得关注”等评价替代事实；
- 禁止以“本文介绍了”“文章主要讲述了”“作者在文中表示”“以下是摘要”“总结如下”等万能句式开头；
- 不面向读者提问，不使用反问，不发出号召，不给出建议，不添加免责声明；
- 最后一句必须完整收束，并以句号、问号或感叹号结束；不得以逗号、顿号、分号、冒号、破折号、括号、斜杠或连接词结尾。

